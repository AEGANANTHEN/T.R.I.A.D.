def _parse_datetime(value: Any) -> datetime | None:
    """
    Convert a value into a Python datetime where possible.

    Supports:
        2024-01-01 08:33:00
        2024-01-01T08:33:00
        ISO timestamps with timezone information
    """

    if isinstance(value, datetime):
        return value

    text = _clean_text(value)

    if not text:
        return None

    try:
        parsed = pd.to_datetime(
            text,
            errors="coerce",
        )

        if pd.isna(parsed):
            return None

        if isinstance(parsed, pd.Timestamp):
            return parsed.to_pydatetime()

    except (TypeError, ValueError):
        return None

    return None


def _parse_time(value: Any) -> time | None:
    """
    Parse HH:MM, HH:MM:SS, or AM/PM time values.
    """

    if isinstance(value, time):
        return value

    text = _clean_text(value)

    if not text:
        return None

    text = text.strip().upper()

    formats = [
        "%H:%M:%S",
        "%H:%M",
        "%I:%M:%S %p",
        "%I:%M %p",
    ]

    for fmt in formats:
        try:
            return datetime.strptime(text, fmt).time()
        except ValueError:
            continue

    return None


def _time_difference_minutes(
    first: time,
    second: time,
) -> float:
    """
    Calculate time-of-day difference in minutes.

    Handles midnight correctly.
    """

    first_seconds = (
        first.hour * 3600
        + first.minute * 60
        + first.second
    )

    second_seconds = (
        second.hour * 3600
        + second.minute * 60
        + second.second
    )

    difference = abs(first_seconds - second_seconds)

    # The shortest path across midnight.
    difference = min(
        difference,
        86400 - difference,
    )

    return difference / 60.0


def _haversine_distance_km(
    latitude_a: float,
    longitude_a: float,
    latitude_b: float,
    longitude_b: float,
) -> float:
    """
    Calculate geographic distance using the Haversine formula.
    """

    from math import asin, cos, radians, sin, sqrt

    earth_radius_km = 6371.0088

    lat1 = radians(latitude_a)
    lat2 = radians(latitude_b)

    delta_lat = radians(latitude_b - latitude_a)
    delta_lon = radians(longitude_b - longitude_a)

    value = (
        sin(delta_lat / 2) ** 2
        + cos(lat1)
        * cos(lat2)
        * sin(delta_lon / 2) ** 2
    )

    value = min(1.0, max(0.0, value))

    return (
        2
        * earth_radius_km
        * asin(sqrt(value))
    )


def _relationship(
    relationship_type: str,
    shared_value: Any,
    correlation_basis: str,
    confidence_score: float,
    entity_a: dict,
    entity_b: dict,
    metadata: dict | None = None,
) -> dict:
    """
    Build a standard cross-evidence relationship.
    """

    return {
        "relationship_type": relationship_type,
        "shared_value": _clean_text(shared_value),
        "correlation_basis": correlation_basis,
        "confidence_score": round(
            max(0.0, min(1.0, confidence_score)),
            4,
        ),
        "entity_a": {
            "entity_type": entity_a.get("entity_type"),
            "value": entity_a.get("value"),
            "normalized_value": entity_a.get("normalized_value"),
            "source": entity_a.get("source"),
            "metadata": entity_a.get("metadata", {}),
        },
        "entity_b": {
            "entity_type": entity_b.get("entity_type"),
            "value": entity_b.get("value"),
            "normalized_value": entity_b.get("normalized_value"),
            "source": entity_b.get("source"),
            "metadata": entity_b.get("metadata", {}),
        },
        "metadata": metadata or {},
    }


