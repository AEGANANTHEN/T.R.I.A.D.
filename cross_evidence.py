# EXACT ENTITY CORRELATION
# ============================================================================

def _correlate_exact_entities(
    evidence_a: dict,
    evidence_b: dict,
) -> list[dict]:
    """
    Correlate strong forensic identifiers using exact normalized matches.

    Supported:
        PHONE
        CELL_ID
        IMEI
        IMSI
    """

    relationships = []

    strong_types = {
        ENTITY_PHONE: "PHONE_MATCH",
        ENTITY_CELL_ID: "CELL_ID_MATCH",
        ENTITY_IMEI: "IMEI_MATCH",
        ENTITY_IMSI: "IMSI_MATCH",
    }

    entities_a = evidence_a.get("entities", [])
    entities_b = evidence_b.get("entities", [])

    index_b: dict[tuple[str, str], list[dict]] = {}

    for entity in entities_b:
        entity_type = entity.get("entity_type")

        if entity_type not in strong_types:
            continue

        normalized = _clean_text(
            entity.get("normalized_value")
        )

        if not normalized:
            continue

        key = (
            entity_type,
            normalized.upper()
            if entity_type == ENTITY_CELL_ID
            else normalized,
        )

        index_b.setdefault(key, []).append(entity)

    seen = set()

    for entity_a in entities_a:

        entity_type = entity_a.get("entity_type")

        if entity_type not in strong_types:
            continue

        normalized_a = _clean_text(
            entity_a.get("normalized_value")
        )

        if not normalized_a:
            continue

        normalized_key = (
            normalized_a.upper()
            if entity_type == ENTITY_CELL_ID
            else normalized_a
        )

        key = (
            entity_type,
            normalized_key,
        )

        matches = index_b.get(key, [])

        for entity_b in matches:

            dedup_key = (
                strong_types[entity_type],
                normalized_key,
            )

            if dedup_key in seen:
                continue

            seen.add(dedup_key)

            relationships.append(
                _relationship(
                    relationship_type=strong_types[entity_type],
                    shared_value=normalized_a,
                    correlation_basis=(
                        f"Exact normalized {entity_type} "
                        f"match across evidence sources."
                    ),
                    confidence_score=CORRELATION_WEIGHTS[
                        strong_types[entity_type]
                    ],
                    entity_a=entity_a,
                    entity_b=entity_b,
                )
            )

    return relationships


