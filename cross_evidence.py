def _normalize_date(value: Any) -> str:
    """
    Normalize common date representations to YYYY-MM-DD.
    """

    text = _clean_text(value)

    if not text:
        return ""

    try:
        parsed = pd.to_datetime(
            text,
            errors="coerce",
            dayfirst=False,
        )

        if pd.isna(parsed):
            return ""

        return parsed.strftime("%Y-%m-%d")

    except (TypeError, ValueError):
        return ""


def _correlate_dates(
    evidence_a: dict,
    evidence_b: dict,
) -> list[dict]:
    """
    Correlate explicit DATE entities and dates contained in TIMESTAMP entities.
    """

    relationships = []

    date_entities_a = [
        entity
        for entity in evidence_a.get("entities", [])
        if entity.get("entity_type") == ENTITY_DATE
    ]

    date_entities_b = [
        entity
        for entity in evidence_b.get("entities", [])
        if entity.get("entity_type") == ENTITY_DATE
    ]

    timestamp_entities_a = [
        entity
        for entity in evidence_a.get("entities", [])
        if entity.get("entity_type") == ENTITY_TIMESTAMP
    ]

    timestamp_entities_b = [
        entity
        for entity in evidence_b.get("entities", [])
        if entity.get("entity_type") == ENTITY_TIMESTAMP
    ]

    # Explicit DATE ↔ DATE.
    for entity_a in date_entities_a:

        date_a = _normalize_date(
            entity_a.get("normalized_value")
        )

        if not date_a:
            continue

        for entity_b in date_entities_b:

            date_b = _normalize_date(
                entity_b.get("normalized_value")
            )

            if date_a != date_b:
                continue

            relationships.append(
                _relationship(
                    relationship_type="DATE_MATCH",
                    shared_value=date_a,
                    correlation_basis=(
                        "Exact normalized calendar-date match "
                        "across evidence sources."
                    ),
                    confidence_score=CORRELATION_WEIGHTS[
                        "DATE_MATCH"
                    ],
                    entity_a=entity_a,
                    entity_b=entity_b,
                )
            )

    # DATE ↔ TIMESTAMP.
    for date_entity in date_entities_a:

        date_value = _normalize_date(
            date_entity.get("normalized_value")
        )

        if not date_value:
            continue

        for timestamp_entity in timestamp_entities_b:

            timestamp_dt = _parse_datetime(
                timestamp_entity.get("normalized_value")
            )

            if timestamp_dt is None:
                continue

            if timestamp_dt.strftime("%Y-%m-%d") != date_value:
                continue

            relationships.append(
                _relationship(
                    relationship_type="DATE_MATCH",
                    shared_value=date_value,
                    correlation_basis=(
                        "Transcript date matches the calendar "
                        "date contained in the CDR timestamp."
                    ),
                    confidence_score=CORRELATION_WEIGHTS[
                        "DATE_MATCH"
                    ],
                    entity_a=date_entity,
                    entity_b=timestamp_entity,
                )
            )

    # Reverse DATE ↔ TIMESTAMP.
    for date_entity in date_entities_b:

        date_value = _normalize_date(
            date_entity.get("normalized_value")
        )

        if not date_value:
            continue

        for timestamp_entity in timestamp_entities_a:

            timestamp_dt = _parse_datetime(
                timestamp_entity.get("normalized_value")
            )

            if timestamp_dt is None:
                continue

            if timestamp_dt.strftime("%Y-%m-%d") != date_value:
                continue

            relationships.append(
                _relationship(
                    relationship_type="DATE_MATCH",
                    shared_value=date_value,
                    correlation_basis=(
                        "Transcript date matches the calendar "
                        "date contained in the CDR timestamp."
                    ),
                    confidence_score=CORRELATION_WEIGHTS[
                        "DATE_MATCH"
                    ],
                    entity_a=timestamp_entity,
                    entity_b=date_entity,
                )
            )

    return relationships


