def _extract_dates(text: str) -> list[dict]:
    entities = []

    for pattern in DATE_PATTERNS:
        for match in pattern.finditer(text):
            value = match.group(0)

            entities.append(
                _entity(
                    ENTITY_DATE,
                    value,
                    value,
                    source="transcript",
                )
            )

    return entities


def _extract_times(text: str) -> list[dict]:
    """
    Extract semantic time-of-day references only.

    TRIAD's generated Faster-Whisper transcript contains audio-segment
    offsets in square brackets.  Those offsets are deliberately removed
    before TIME extraction because they describe audio position rather than
    an event time.

    Duplicate semantic times are collapsed because EvidenceRelationship
    represents a correlation between evidence values, not individual text
    occurrences.
    """

    # Remove generated Faster-Whisper segment labels first.
    cleaned_text = GENERATED_TRANSCRIPT_SEGMENT_PATTERN.sub("", text)

    entities = []
    seen_times: set[str] = set()

    for match in TIME_PATTERN.finditer(cleaned_text):
        value = match.group("value").strip()
        normalized = value.upper()

        if normalized in seen_times:
            continue

        seen_times.add(normalized)

        entities.append(
            _entity(
                ENTITY_TIME,
                value,
                normalized,
                source="transcript",
                metadata={
                    "extraction_basis": "semantic_time_reference",
                },
            )
        )

    return entities


def extract_transcript_entities(text: str) -> dict:
    """
    Extract forensic entities from transcript text.

    Returns:
        {
            "entities": [...],
            "entity_count": int,
            "by_type": {
                "PHONE": [...],
                ...
            }
        }
    """

    text = _clean_text(text)
    text = _generated_transcript_body(text)

    entities = []

    if not text:
        return {
            "entities": [],
            "entity_count": 0,
            "by_type": {},
        }

    entities.extend(_extract_phones(text))
    entities.extend(_extract_imei(text))
    entities.extend(_extract_imsi(text))
    entities.extend(_extract_cell_ids(text))
    entities.extend(_extract_coordinates(text))
    entities.extend(_extract_latitudes(text))
    entities.extend(_extract_longitudes(text))
    entities.extend(_extract_timestamps(text))
    entities.extend(_extract_dates(text))
    entities.extend(_extract_times(text))

    return _build_entity_result(entities)


# ============================================================================
# CDR ENTITY EXTRACTION
# ============================================================================

def extract_cdr_entities(df: pd.DataFrame) -> dict:
    """
    Extract entities from a normalized CDR DataFrame.

    Expected normalized columns may include:
        caller
        receiver
        timestamp
        cell_id
        lat
        lon
        imei
        imsi
    """

    if df is None or df.empty:
        return {
            "entities": [],
            "entity_count": 0,
            "by_type": {},
        }

    entities = []

    for row_index, row in df.iterrows():

        # CALLER
        caller = _clean_text(row.get("caller"))

        if caller:
            normalized = _normalize_phone(caller)

            if _valid_phone(normalized):
                entities.append(
                    _entity(
                        ENTITY_PHONE,
                        caller,
                        normalized,
                        source="cdr",
                        metadata={
                            "role": "caller",
                            "row_index": row_index,
                        },
                    )
                )

        # RECEIVER
        receiver = _clean_text(row.get("receiver"))

        if receiver:
            normalized = _normalize_phone(receiver)

            if _valid_phone(normalized):
                entities.append(
                    _entity(
                        ENTITY_PHONE,
                        receiver,
                        normalized,
                        source="cdr",
                        metadata={
                            "role": "receiver",
                            "row_index": row_index,
                        },
                    )
                )

        # TIMESTAMP
        timestamp = row.get("timestamp")

        if timestamp is not None and not (
            isinstance(timestamp, float) and pd.isna(timestamp)
        ):
            timestamp_text = _clean_text(timestamp)

            if timestamp_text:
                entities.append(
                    _entity(
                        ENTITY_TIMESTAMP,
                        timestamp_text,
                        timestamp_text,
                        source="cdr",
                        metadata={
                            "row_index": row_index,
                        },
                    )
                )

        # CELL ID
        cell_id = _clean_text(row.get("cell_id"))

        if cell_id:
            entities.append(
                _entity(
                    ENTITY_CELL_ID,
                    cell_id,
                    cell_id.upper(),
                    source="cdr",
                    metadata={
                        "row_index": row_index,
                    },
                )
            )

        # LATITUDE
        lat = _safe_float(row.get("lat"))

        if lat is not None and -90 <= lat <= 90:
            entities.append(
                _entity(
                    ENTITY_LATITUDE,
                    lat,
                    lat,
                    source="cdr",
                    metadata={
                        "row_index": row_index,
                    },
                )
            )

        # LONGITUDE
        lon = _safe_float(row.get("lon"))

        if lon is not None and -180 <= lon <= 180:
            entities.append(
                _entity(
                    ENTITY_LONGITUDE,
                    lon,
                    lon,
                    source="cdr",
                    metadata={
                        "row_index": row_index,
                    },
                )
            )

        # IMEI
        imei = _clean_text(row.get("imei"))

        if imei:
            entities.append(
                _entity(
                    ENTITY_IMEI,
                    imei,
                    imei,
                    source="cdr",
                    metadata={
                        "row_index": row_index,
                    },
                )
            )

        # IMSI
        imsi = _clean_text(row.get("imsi"))

        if imsi:
            entities.append(
                _entity(
                    ENTITY_IMSI,
                    imsi,
                    imsi,
                    source="cdr",
                    metadata={
                        "row_index": row_index,
                    },
                )
            )

    return _build_entity_result(entities)


# ============================================================================
# GENERIC TEXT EXTRACTION
# ============================================================================

def extract_text_entities(text: str, source: str = "text") -> dict:
    """
    Generic entity extraction from arbitrary text.

    This uses the transcript extractor and changes the source label.
    """

    result = extract_transcript_entities(text)

    for entity in result["entities"]:
        entity["source"] = source

    return result


# ============================================================================
# RESULT BUILDING
# ============================================================================

def _build_entity_result(entities: list[dict]) -> dict:
    by_type: dict[str, list[dict]] = {}

    for entity in entities:
        entity_type = entity["entity_type"]
        by_type.setdefault(entity_type, []).append(entity)

    return {
        "entities": entities,
        "entity_count": len(entities),
        "by_type": by_type,
    }


# ============================================================================
# CDR FILE EXTRACTION
# ============================================================================

def extract_cdr_entities_from_file(file_path: str | Path) -> dict:
    """
    Load a CDR file using the existing CDRNormalizer and extract entities.

    The existing CDR engine remains responsible for CDR normalization.
    """

    from cdr_engine import CDRNormalizer

    path = Path(file_path)

    if not path.exists():
        raise FileNotFoundError(
            f"CDR file not found: {path}"
        )

    # Current actual CDRNormalizer API.
    normalizer = CDRNormalizer(str(path))

    df = normalizer.df
    metadata = normalizer.metadata

    result = extract_cdr_entities(df)

    result["file"] = str(path)
    result["sha256"] = normalizer.sha256
    result["metadata"] = metadata

    return result


