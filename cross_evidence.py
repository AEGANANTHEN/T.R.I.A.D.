def correlate_cdr_with_transcript(
    cdr_evidence: dict,
    transcript_evidence: dict,
    *,
    time_tolerance_minutes: int = DEFAULT_TIME_TOLERANCE_MINUTES,
    location_tolerance_km: float = DEFAULT_LOCATION_TOLERANCE_KM,
) -> dict:
    """
    Convenience wrapper specifically for:

        CDR evidence ↔ transcript evidence

    The actual correlation logic is handled by correlate_evidence().
    """

    result = correlate_evidence(
        cdr_evidence,
        transcript_evidence,
        time_tolerance_minutes=time_tolerance_minutes,
        location_tolerance_km=location_tolerance_km,
    )

    result["source_a_type"] = "CDR"
    result["source_b_type"] = "TRANSCRIPT"

    return result


# ============================================================================
# RELATIONSHIP CONVERSION FOR DEMS
# ============================================================================

def build_evidence_relationship_records(
    correlation_result: dict,
    *,
    source_evidence_id: int,
    target_evidence_id: int,
    case_id: int | None = None,
    created_by_id: int | None = None,
) -> list[dict]:
    """
    Convert correlation results into dictionaries matching the
    EvidenceRelationship database model.

    This function does NOT write to the database.

    Database persistence will be handled by dem_routes.py.
    """

    records = []

    for relationship in correlation_result.get(
        "relationships",
        [],
    ):

        records.append(
            {
                "case_id": case_id,
                "source_evidence_id": source_evidence_id,
                "target_evidence_id": target_evidence_id,
                "relationship_type": relationship.get(
                    "relationship_type"
                ),
                "shared_value": relationship.get(
                    "shared_value"
                ),
                "correlation_basis": relationship.get(
                    "correlation_basis"
                ),
                "confidence_score": relationship.get(
                    "confidence_score"
                ),
                "metadata_json": json.dumps(
                    {
                        "entity_a": relationship.get(
                            "entity_a",
                            {},
                        ),
                        "entity_b": relationship.get(
                            "entity_b",
                            {},
                        ),
                        "metadata": relationship.get(
                            "metadata",
                            {},
                        ),
                    },
                    ensure_ascii=False,
                    default=str,
                ),
                "created_by_id": created_by_id,
            }
        )

    return records


