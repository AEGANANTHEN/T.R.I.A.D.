PHONE_PATTERN = re.compile(
    r"""
    (?<!\d)
    (?:\+91[\s-]?)?
    (?:[6-9]\d{9})
    (?!\d)
    """,
    re.VERBOSE,
)


IMEI_PATTERN = re.compile(
    r"""
    \b
    IMEI
    (?:\s*(?:NO|NUMBER))?
    \s*(?::|=|\#|-|IS|NO\.?|NUMBER)?\s*
    (?P<value>\d{14,17})
    \b
    """,
    re.IGNORECASE | re.VERBOSE,
)


IMSI_LABELLED_PATTERN = re.compile(
    r"""
    \b
    IMSI
    (?:\s*(?:NO|NUMBER))?
    \s*(?::|=|\#|-|IS|NO\.?|NUMBER)?\s*
    (?P<value>\d{10,16})
    \b
    """,
    re.IGNORECASE | re.VERBOSE,
)


# IMPORTANT:
# Match the complete phrase "cell tower CELL001" / "cell id CELL001"
# rather than separately extracting "tower" and "001".
CELL_ID_PATTERN = re.compile(
    r"""
    \b
    (?:
        cell\s+tower
        |
        cell\s+id
        |
        cell\s+identifier
        |
        tower\s+id
        |
        tower
        |
        cgi
        |
        cgid
        |
        site\s+id
        |
        cell
    )
    \s*[:=#-]?\s*
    (?P<value>
        [A-Za-z]{1,8}[-_]?\d{1,12}
        |
        \d{2,15}
    )
    \b
    """,
    re.IGNORECASE | re.VERBOSE,
)


COORDINATE_PATTERN = re.compile(
    r"""
    (?P<lat>[+-]?\d{1,2}(?:\.\d+)?)
    \s*[,/]\s*
    (?P<lon>[+-]?\d{1,3}(?:\.\d+)?)
    """,
    re.VERBOSE,
)


LATITUDE_PATTERN = re.compile(
    r"""
    \b
    latitude
    \s*[:=]?\s*
    (?P<value>[+-]?\d{1,2}(?:\.\d+)?)
    """,
    re.IGNORECASE | re.VERBOSE,
)


LONGITUDE_PATTERN = re.compile(
    r"""
    \b
    longitude
    \s*[:=]?\s*
    (?P<value>[+-]?\d{1,3}(?:\.\d+)?)
    """,
    re.IGNORECASE | re.VERBOSE,
)


DATE_PATTERNS = [
    re.compile(r"\b\d{4}-\d{2}-\d{2}\b"),
    re.compile(r"\b\d{2}/\d{2}/\d{4}\b"),
    re.compile(r"\b\d{2}-\d{2}-\d{4}\b"),
]


TIME_PATTERN = re.compile(
    r"""
    \b
    (?P<value>
        (?:[01]?\d|2[0-3]):[0-5]\d
        (?::[0-5]\d)?
        |
        (?:1[0-2]|0?[1-9]):[0-5]\d\s*(?:AM|PM)
    )
    \b
    """,
    re.IGNORECASE | re.VERBOSE,
)


# Faster-Whisper transcript documents generated by TRIAD contain technical
# segment timecodes such as:
#     [000:00:04.00 - 000:00:09.00] spoken text
# These are audio offsets, NOT real-world event times.  They must never be
# correlated against CDR timestamps as TIME entities.
GENERATED_TRANSCRIPT_SEGMENT_PATTERN = re.compile(
    r"\[\s*\d{1,3}:\d{2}:\d{2}(?:\.\d+)?\s*-\s*"
    r"\d{1,3}:\d{2}:\d{2}(?:\.\d+)?\s*\]\s*"
)


ISO_TIMESTAMP_PATTERN = re.compile(
    r"""
    \b
    \d{4}-\d{2}-\d{2}
    [T\s]
    \d{2}:\d{2}
    (?::\d{2})?
    (?:\.\d+)?
    (?:Z|[+-]\d{2}:?\d{2})?
    \b
    """,
    re.VERBOSE,
)


