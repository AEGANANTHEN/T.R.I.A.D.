def _clean_text(value: Any) -> str:
    """Convert a value to clean text."""

    if value is None:
        return ""

    if isinstance(value, float) and pd.isna(value):
        return ""

    # Preserve integer-like numeric identifiers without a trailing ".0".
    # This is important for IMEI/IMSI values loaded by pandas.
    if isinstance(value, float) and value.is_integer():
        return str(int(value))

    return str(value).strip()


def _normalize_phone(value: str) -> str:
    """Normalize Indian phone numbers to a 10-digit representation."""

    digits = re.sub(r"\D", "", value)

    if digits.startswith("0091"):
        digits = digits[4:]

    elif digits.startswith("91") and len(digits) == 12:
        digits = digits[2:]

    return digits


def _valid_phone(value: str) -> bool:
    """Check whether a normalized phone number looks valid."""

    return bool(re.fullmatch(r"[6-9]\d{9}", value))


def _safe_float(value: Any) -> float | None:
    """Safely convert a value to float."""

    try:
        if value is None:
            return None

        if isinstance(value, float) and pd.isna(value):
            return None

        return float(value)

    except (TypeError, ValueError):
        return None


def _entity(
    entity_type: str,
    value: Any,
    normalized_value: Any = None,
    source: str = "unknown",
    metadata: dict | None = None,
) -> dict:
    """Build a standard entity dictionary."""

    clean_value = _clean_text(value)

    if normalized_value is None:
        normalized_value = clean_value

    return {
        "entity_type": entity_type,
        "value": clean_value,
        "normalized_value": _clean_text(normalized_value),
        "source": source,
        "metadata": metadata or {},
    }


