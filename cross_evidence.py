# EXACT CROSS-EVIDENCE OVERLAP
# ============================================================================

def summarize_entity_overlap(
    evidence_a: dict,
    evidence_b: dict,
) -> dict:
    """
    Find exact normalized entity overlaps between two evidence sources.
    """

    overlaps = []

    entities_a = evidence_a.get("entities", [])
    entities_b = evidence_b.get("entities", [])

    index_b: dict[tuple[str, str], list[dict]] = {}

    for entity in entities_b:
        key = (
            entity["entity_type"],
            entity["normalized_value"],
        )

        index_b.setdefault(key, []).append(entity)

    seen = set()

    for entity in entities_a:
        key = (
            entity["entity_type"],
            entity["normalized_value"],
        )

        if key not in index_b:
            continue

        for matching_entity in index_b[key]:

            overlap_key = (
                key,
                entity.get("source"),
                matching_entity.get("source"),
            )

            if overlap_key in seen:
                continue

            seen.add(overlap_key)

            overlaps.append(
                {
                    "entity_type": entity["entity_type"],
                    "normalized_value": entity["normalized_value"],
                    "evidence_a_source": entity.get("source"),
                    "evidence_b_source": matching_entity.get("source"),
                    "evidence_a_metadata": entity.get(
                        "metadata",
                        {},
                    ),
                    "evidence_b_metadata": matching_entity.get(
                        "metadata",
                        {},
                    ),
                }
            )

    return {
        "overlap_count": len(overlaps),
        "overlaps": overlaps,
    }


