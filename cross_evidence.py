# ============================================================================

def _correlate_timestamps(
    evidence_a: dict,
    evidence_b: dict,
    time_tolerance_minutes: int,
) -> list[dict]:
    """
    Correlate full timestamps between evidence sources.
    """

    relationships = []

    timestamps_a = [
        entity
        for entity in evidence_a.get("entities", [])
        if entity.get("entity_type") == ENTITY_TIMESTAMP
    ]

    timestamps_b = [
        entity
        for entity in evidence_b.get("entities", [])
        if entity.get("entity_type") == ENTITY_TIMESTAMP
    ]

    for entity_a in timestamps_a:

        dt_a = _parse_datetime(
            entity_a.get("normalized_value")
        )

        if dt_a is None:
            continue

        for entity_b in timestamps_b:

            dt_b = _parse_datetime(
                entity_b.get("normalized_value")
            )

            if dt_b is None:
                continue

            difference_minutes = abs(
                (dt_a - dt_b).total_seconds()
            ) / 60.0

            if difference_minutes > time_tolerance_minutes:
                continue

            if time_tolerance_minutes <= 0:
                confidence = 1.0
            else:
                confidence = (
                    1.0
                    - (
                        difference_minutes
                        / time_tolerance_minutes
                    )
                    * 0.20
                )

            relationships.append(
                _relationship(
                    relationship_type="TIMESTAMP_MATCH",
                    shared_value=(
                        f"{dt_a.isoformat()} ↔ "
                        f"{dt_b.isoformat()}"
                    ),
                    correlation_basis=(
                        f"Timestamp difference is "
                        f"{difference_minutes:.2f} minutes, "
                        f"within the configured "
                        f"{time_tolerance_minutes}-minute tolerance."
                    ),
                    confidence_score=min(
                        CORRELATION_WEIGHTS["TIMESTAMP_MATCH"],
                        confidence,
                    ),
                    entity_a=entity_a,
                    entity_b=entity_b,
                    metadata={
                        "difference_minutes": round(
                            difference_minutes,
                            4,
                        ),
                        "tolerance_minutes": (
                            time_tolerance_minutes
                        ),
                    },
                )
            )

    return relationships


