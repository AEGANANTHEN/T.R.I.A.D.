# CDR TIMESTAMP ↔ TRANSCRIPT TIME CORRELATION
# ============================================================================

def _correlate_cdr_timestamp_to_time(
    evidence_a: dict,
    evidence_b: dict,
    time_tolerance_minutes: int,
) -> list[dict]:
    """
    Correlate CDR timestamps against transcript time-of-day entities.

    For forensic correlation, this function deliberately avoids generating
    every possible timestamp within the tolerance window.

    Priority:
        1. If a CDR row shares a strong identifier with the transcript
           (PHONE, CELL_ID, IMEI, or IMSI), compare the transcript time only
           against timestamps from those anchored rows.
        2. If no strong identifier anchor exists, compare against only the
           nearest CDR timestamp(s) for each transcript time.

    This prevents a single transcript time such as 08:33 from producing a
    large number of weak TIME_MATCH relationships merely because many CDR
    records happened to occur within +/- 15 minutes.
    """

    strong_types = {
        ENTITY_PHONE,
        ENTITY_CELL_ID,
        ENTITY_IMEI,
        ENTITY_IMSI,
    }

    def _normalized_key(entity: dict) -> tuple[str, str]:
        entity_type = entity.get("entity_type", "")
        value = _clean_text(entity.get("normalized_value"))
        if entity_type == ENTITY_CELL_ID:
            value = value.upper()
        return entity_type, value

    def _strong_keys(evidence: dict) -> set[tuple[str, str]]:
        keys = set()
        for entity in evidence.get("entities", []):
            entity_type = entity.get("entity_type")
            if entity_type not in strong_types:
                continue
            key = _normalized_key(entity)
            if key[1]:
                keys.add(key)
        return keys

    def _build_strong_row_indexes(evidence: dict) -> set[Any]:
        """
        Return CDR row indexes that contain at least one strong identifier
        also present in the opposite evidence source.
        """
        result = set()
        return result

    def _timestamp_entities(evidence: dict) -> list[dict]:
        return [
            entity
            for entity in evidence.get("entities", [])
            if entity.get("entity_type") == ENTITY_TIMESTAMP
        ]

    def _time_entities(evidence: dict) -> list[dict]:
        return [
            entity
            for entity in evidence.get("entities", [])
            if entity.get("entity_type") == ENTITY_TIME
        ]

    # This function is currently intended primarily for CDR -> transcript,
    # but keep the direction handling symmetric.
    timestamps_a = _timestamp_entities(evidence_a)
    times_a = _time_entities(evidence_a)
    timestamps_b = _timestamp_entities(evidence_b)
    times_b = _time_entities(evidence_b)

    if timestamps_a and times_b:
        cdr_timestamps = timestamps_a
        transcript_times = times_b
        cdr_evidence = evidence_a
        transcript_evidence = evidence_b
    elif timestamps_b and times_a:
        cdr_timestamps = timestamps_b
        transcript_times = times_a
        cdr_evidence = evidence_b
        transcript_evidence = evidence_a
    else:
        return []

    transcript_strong_keys = _strong_keys(transcript_evidence)

    # Build the CDR row -> strong identifiers map.
    row_to_strong_keys: dict[Any, set[tuple[str, str]]] = {}
    for entity in cdr_evidence.get("entities", []):
        entity_type = entity.get("entity_type")
        if entity_type not in strong_types:
            continue

        metadata = entity.get("metadata", {}) or {}
        row_index = metadata.get("row_index")
        if row_index is None:
            continue

        key = _normalized_key(entity)
        if key[1]:
            row_to_strong_keys.setdefault(row_index, set()).add(key)

    anchored_row_indexes = {
        row_index
        for row_index, keys in row_to_strong_keys.items()
        if keys.intersection(transcript_strong_keys)
    }

    # Keep only CDR timestamps from anchored rows when an anchor exists.
    if anchored_row_indexes:
        candidate_timestamps = [
            entity
            for entity in cdr_timestamps
            if (entity.get("metadata", {}) or {}).get("row_index")
            in anchored_row_indexes
        ]
        anchor_mode = True

        # Safety fallback if malformed metadata prevented candidate selection.
        if not candidate_timestamps:
            candidate_timestamps = cdr_timestamps
            anchor_mode = False
    else:
        candidate_timestamps = cdr_timestamps
        anchor_mode = False

    relationships = []

    # A transcript can contain the same time more than once because the
    # entity extractor may encounter repeated mentions such as "00:04:00".
    # Treat identical normalized times as one forensic time point so that
    # the same TIME_MATCH is not stored repeatedly.
    seen_transcript_times: set[str] = set()

    for transcript_time_entity in transcript_times:
        normalized_transcript_time = _clean_text(
            transcript_time_entity.get("normalized_value")
        )

        transcript_time = _parse_time(
            normalized_transcript_time
        )

        if transcript_time is None:
            continue

        transcript_time_key = transcript_time.strftime("%H:%M:%S")

        if transcript_time_key in seen_transcript_times:
            continue

        seen_transcript_times.add(transcript_time_key)

        candidates = []

        for timestamp_entity in candidate_timestamps:
            timestamp_dt = _parse_datetime(
                timestamp_entity.get("normalized_value")
            )

            if timestamp_dt is None:
                continue

            timestamp_time = timestamp_dt.time()

            difference_minutes = _time_difference_minutes(
                timestamp_time,
                transcript_time,
            )

            if difference_minutes <= time_tolerance_minutes:
                candidates.append(
                    (
                        difference_minutes,
                        timestamp_entity,
                        timestamp_dt,
                        timestamp_time,
                    )
                )

        if not candidates:
            continue

        # Keep exactly ONE best timestamp for each transcript time.
        #
        # Earlier versions retained every candidate tied at the minimum
        # distance.  For DEMS forensic correlation that can create multiple
        # weak TIME_MATCH records for one transcript timestamp.  We instead
        # choose one deterministic nearest CDR timestamp.
        #
        # Sorting priority:
        #   1. smallest time difference
        #   2. earliest CDR datetime
        #   3. row index, when available
        #
        # Strong-identifier anchor mode still restricts the candidates before
        # this selection, so an anchored row always has priority.
        def _candidate_sort_key(candidate):
            difference, entity, timestamp_dt, _timestamp_time = candidate
            metadata = entity.get("metadata", {}) or {}
            row_index = metadata.get("row_index")
            try:
                row_sort_value = int(row_index)
            except (TypeError, ValueError):
                row_sort_value = 10**12

            return (
                difference,
                timestamp_dt,
                row_sort_value,
            )

        selected_candidates = [
            min(
                candidates,
                key=_candidate_sort_key,
            )
        ]

        for (
            difference_minutes,
            timestamp_entity,
            timestamp_dt,
            timestamp_time,
        ) in selected_candidates:
            if time_tolerance_minutes <= 0:
                confidence = 1.0
            else:
                confidence = (
                    1.0
                    - (
                        difference_minutes
                        / time_tolerance_minutes
                    )
                    * 0.20
                )

            if anchor_mode:
                basis = (
                    "Transcript time matches the nearest CDR timestamp "
                    "from a CDR row anchored by an exact PHONE/CELL_ID/"
                    "IMEI/IMSI match."
                )
                relationship_confidence = min(
                    0.98,
                    max(
                        CORRELATION_WEIGHTS["TIME_MATCH"],
                        confidence,
                    ),
                )
            else:
                basis = (
                    "Transcript time matches the nearest CDR timestamp "
                    "within the configured tolerance; no strong "
                    "identifier anchor was available."
                )
                relationship_confidence = min(
                    CORRELATION_WEIGHTS["TIME_MATCH"],
                    confidence,
                )

            relationships.append(
                _relationship(
                    relationship_type="TIME_MATCH",
                    shared_value=(
                        f"{timestamp_time.strftime('%H:%M:%S')} "
                        f"↔ "
                        f"{transcript_time.strftime('%H:%M:%S')}"
                    ),
                    correlation_basis=basis,
                    confidence_score=relationship_confidence,
                    entity_a=timestamp_entity,
                    entity_b=transcript_time_entity,
                    metadata={
                        "difference_minutes": round(
                            difference_minutes,
                            4,
                        ),
                        "tolerance_minutes": (
                            time_tolerance_minutes
                        ),
                        "cdr_datetime": (
                            timestamp_dt.isoformat()
                        ),
                        "strong_identifier_anchor": anchor_mode,
                        "anchored_row_indexes": (
                            sorted(
                                str(index)
                                for index in anchored_row_indexes
                            )
                            if anchor_mode
                            else []
                        ),
                    },
                )
            )

    return relationships


